"""Experiment 12b: Global permutation test for experiment 12 (multiplicity-corrected).

Experiment 12 scanned 20 cells (2 dose measures x 10 horizons) and the largest top-rest
difference was acc5/day10 ~ +3pp. One borderline cell out of 20 is expected under pure noise,
so here we ask the single corrected question: "if accumulated toxicity had NO relation to
future returns, how often would a scan this size produce a max top-rest at least this large?"

Rules fixed BEFORE running (2026-10-13):
- Null is generated by permuting DATES: each falling-day row on date d receives the dose its
  own symbol had on date sigma(d) (random permutation of falling dates; rows whose symbol has
  no falling day on sigma(d) are dropped). This keeps the same-date cross-sectional clustering
  of doses and the autocorrelation of returns — shuffling rows independently would make the
  null too easy to beat.
- Test statistic = max over all 20 cells of the top-quintile-minus-rest difference
  (signed max, since the hypothesis is one-sided: more rage -> better returns).
- p = fraction of 1000 permutations whose max >= the observed max. Verdict: p < 0.05 passes.
Run: python3 exp12b_permutation.py

Result (2026-10-13, 289 falling days, Jul 20 - Oct 9):
- observed max top-rest +3.09pp; permutation null median +2.29pp, 95th pct +6.11pp
- global p = 0.341 -> FAILS decisively. A no-effect world produces a drift this large in a
  20-cell scan about 1 time in 3; the null's MEDIAN (+2.29pp) is nearly our observed value.
- Reading: the day 7-10 "upward drift" in experiment 12 is fully explained by scan size.
  Experiment 12's pre-registered re-test (post-10/13 data) stays open but expectations are low.
"""
import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
WARMUP, BINS, HMAX, NPERM = 10, 5, 10, 1000

# same pipeline as experiment 12
posts = pd.read_sql("SELECT uuid, symbol, created_at FROM posts", sqlite3.connect(HERE / "data" / "community.db"))
posts = posts.merge(pd.read_csv(HERE / "data" / "toxicity.csv", usecols=["uuid", "toxicity"]), on="uuid")
prices = pd.read_csv(HERE / "data" / "prices.csv", parse_dates=["date"])
prices = prices[prices.date < pd.Timestamp.now().normalize()]
days = np.sort(prices.date.unique())
et = pd.to_datetime(posts.created_at, utc=True).dt.tz_convert("America/New_York")
cal = et.dt.normalize().dt.tz_localize(None) + pd.to_timedelta((et.dt.hour >= 16).astype(int), unit="D")
idx = np.searchsorted(days, cal.values)
posts = posts[idx < len(days)].copy()
posts["date"] = days[idx[idx < len(days)]]
daily = posts.groupby(["symbol", "date"]).agg(tox=("toxicity", "mean")).reset_index()

px = prices.pivot(index="date", columns="symbol", values="close").pct_change()
ex = px.drop(columns="SPY").sub(px.SPY, axis=0).stack().rename("ex").reset_index()
df = ex.merge(daily, on=["symbol", "date"], how="inner").sort_values(["symbol", "date"]).reset_index(drop=True)
g = df.groupby("symbol")
df["tox_rel"] = df.tox - g.tox.transform(lambda x: x.expanding(WARMUP).mean().shift(1))
df["acc3"] = g.tox_rel.transform(lambda x: x.rolling(3).mean())
df["acc5"] = g.tox_rel.transform(lambda x: x.rolling(5).mean())
df["drop3"] = g.ex.transform(lambda x: x.rolling(3).sum())
for k in range(1, HMAX + 1):
    df[f"c{k}"] = g.ex.transform(lambda x, k=k: sum(x.shift(-j) for j in range(1, k + 1)))
df = df.dropna(subset=["acc3", "acc5", "drop3", "c1"])
df["falling"] = df.groupby("symbol").drop3.transform(lambda x: x <= x.quantile(1 / 3))
fall = df[df.falling].reset_index(drop=True)
COLS = [f"c{k}" for k in range(1, HMAX + 1)]


def max_stat(d):
    """Max top-quintile-minus-rest over both measures and all horizons."""
    best = -np.inf
    for meas in ("acc3", "acc5"):
        dd = d.dropna(subset=[meas])
        q = pd.qcut(dd[meas].rank(method="first"), BINS, labels=False)
        top = q == BINS - 1
        for col in COLS:
            v = dd[col]
            m = v.notna()
            if (m & top).sum() and (m & ~top).sum():
                best = max(best, v[m & top].mean() - v[m & ~top].mean())
    return best


obs = max_stat(fall)
dates = fall.date.unique()
dose = fall.set_index(["symbol", "date"])[["acc3", "acc5"]]
rng = np.random.default_rng(0)
hits, maxes = 0, []
for i in range(NPERM):
    sigma = dict(zip(dates, rng.permutation(dates)))
    perm = fall[["symbol", "date"] + COLS].copy()
    key = pd.MultiIndex.from_arrays([perm.symbol, perm.date.map(sigma)])
    perm[["acc3", "acc5"]] = dose.reindex(key).to_numpy()
    perm = perm.dropna(subset=["acc3", "acc5"])
    maxes.append(max_stat(perm))

maxes = np.array(maxes)
p = (maxes >= obs).mean()
print(f"falling days {len(fall)}, period {fall.date.min():%Y-%m-%d} ~ {fall.date.max():%Y-%m-%d}")
print(f"observed max top-rest = {obs * 100:+.2f}pp (over 2 measures x {HMAX} horizons)")
print(f"permutation null ({NPERM} date-permutations): median {np.median(maxes) * 100:+.2f}pp, "
      f"95th pct {np.percentile(maxes, 95) * 100:+.2f}pp")
print(f"global p = {p:.3f}  ->  {'PASSES (<0.05): unlikely to be pure noise' if p < 0.05 else 'FAILS: a scan this size produces a drift this large by chance'}")
